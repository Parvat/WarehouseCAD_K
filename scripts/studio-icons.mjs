// Copies the Studio icon set out of design/studio/Icons.dc.html into src/studio/iconData.js — the exact SVG markup,
// nothing redrawn (STUDIO.md §9). Run after the design file changes: node scripts/studio-icons.mjs
//   TOOLS:   the "D tools" section, each pair idle · active (24px)
//   RAIL:    the rail in the box section: Floor plans, Racking, Ops, Structural, Safety, Zones, Blocks (24px)
//   OBJECTS: the box section's object tiles (48px drawings of a 24px grid)
import fs from 'node:fs'

const SRC = process.argv[2] || 'design/studio/Icons.dc.html', OUT = 'src/studio/iconData.js'
const html = fs.readFileSync(SRC, 'utf8')
const lines = html.split('\n')
const inner = (svg) => ({ viewBox: (svg.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 24 24', size: Number((svg.match(/width="(\d+)"/) || [])[1] || 24), body: svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '') })

/* the tools grid: each cell is a column with two svgs (idle, active) and its label */
const toolsLine = lines.find(l => /grid-template-columns: repeat\(11/.test(l))
if (!toolsLine) throw new Error('tools grid not found')
const TOOLS = {}
for (const cell of toolsLine.split('<div style="display: flex; flex-direction: column; align-items: center; gap: 6px;').slice(1)) {
  const svgs = [...cell.matchAll(/<svg[\s\S]*?<\/svg>/g)].map(m => m[0])
  const label = (cell.match(/<\/span><span[^>]*>([A-Za-z][A-Za-z ]*)<\/span><\/div>/) || cell.match(/>([A-Z][A-Za-z ]+)<\/span>\s*<\/div>/) || [])[1]
  if (!label || svgs.length < 2) continue
  TOOLS[label.trim()] = { idle: inner(svgs[0]), active: inner(svgs[1]) }
}

/* the rail: spans with a title, in the first (box) section */
const boxLine = lines.find(l => /<span title="Floor plans"/.test(l))
const RAIL_NAMES = ['Floor plans', 'Racking', 'Ops', 'Structural', 'Safety', 'Zones', 'Blocks']
const RAIL = {}
for (const m of boxLine.matchAll(/<span title="([^"]+)" style="[^"]*">(<svg[\s\S]*?<\/svg>)<\/span>/g)) if (!RAIL[m[1]] && RAIL_NAMES.includes(m[1])) RAIL[m[1]] = inner(m[2])

/* object tiles (48px): an svg followed by its label */
const OBJECTS = {}
for (const m of boxLine.matchAll(/(<svg width="48"[\s\S]*?<\/svg>)\s*<span[^>]*>([^<]+)<\/span>/g)) if (!OBJECTS[m[2].trim()]) OBJECTS[m[2].trim()] = inner(m[1])

const banner = `// GENERATED by scripts/studio-icons.mjs from ${SRC} — do not edit by hand (STUDIO.md §9: one icon set, box style).\n`
fs.writeFileSync(OUT, banner +
  `export const TOOLS = ${JSON.stringify(TOOLS, null, 1)}\n` +
  `export const RAIL = ${JSON.stringify(RAIL, null, 1)}\n` +
  `export const OBJECTS = ${JSON.stringify(OBJECTS, null, 1)}\n`)
console.log('tools:', Object.keys(TOOLS).join(', '))
console.log('rail:', Object.keys(RAIL).join(', '))
console.log('objects:', Object.keys(OBJECTS).length)
