// ST — the Studio frame, step 1 (STUDIO.md §1, §5, §9; design/studio/Studio.dc.html screen C1): the canvas fills the
// window and the islands float on it with the mockup's values; every icon comes from design/studio/Icons.dc.html
// (src/studio/iconData.js, generated); no Lucide or line icons in the frame.
import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { TOOLS, RAIL } from '../../studio/iconData'

const read = (p) => readFileSync(new URL('../../' + p, import.meta.url), 'utf8').split('\r\n').join('\n')
const FRAME = ['studio/StudioFrame.jsx', 'studio/StudioTools.jsx', 'studio/Icon.jsx', 'App.jsx', 'components/Toolbar/TopBar.jsx', 'canvas2/Canvas2.jsx']

describe('ST — the frame', () => {
  it('ST-islands: top-left, top-right, rail, flyout, right card, tool pill, bottom-left, bottom-right at the mockup\'s places and sizes', () => {
    const f = read('studio/StudioFrame.jsx'), t = read('studio/StudioTools.jsx'), css = read('studio/studio.css')
    expect(f).toMatch(/data-island="top-left" style=\{\{ left: 16, top: 16, height: 44, gap: 10, padding: '0 12px 0 14px' \}\}/)
    expect(f).toMatch(/data-island="top-right" style=\{\{ right: 16, top: 16, height: 44, gap: 4, padding: '0 6px' \}\}/)
    expect(f).toMatch(/right: 16, top: 76, width: 300, maxHeight: 'calc\(100vh - 152px\)'/)
    expect(f).toMatch(/data-island="bottom-left" style=\{\{ left: 16, bottom: 20, height: 40, gap: 2, padding: '0 4px' \}\}/)
    expect(f).toMatch(/data-island="bottom-right" style=\{\{ right: 16, bottom: 20, height: 40, gap: 2, padding: '0 4px' \}\}/)
    expect(t).toMatch(/data-island="rail" style=\{\{ left: 16, top: 76, width: 48, flexDirection: 'column', gap: 4, padding: '6px 0' \}\}/)
    expect(t).toMatch(/style=\{\{ left: 72, top: 76, width: 232, flexDirection: 'column', alignItems: 'stretch', padding: 6/)
    expect(t).toMatch(/style=\{\{ left: '50%', bottom: 20, transform: 'translateX\(-50%\)', gap: 2, padding: 5 \}\}/)
    // islands and pill: the mockup's surface, line, radius and shadow
    expect(css).toMatch(/\.st-island \{[\s\S]*?background:#1F2321; border:1px solid #323835; border-radius:10px; box-shadow:0 8px 24px rgba\(15,18,16,\.18\);/)
    expect(css).toMatch(/\.st-pill \{[\s\S]*?background:#1F2321; border:1px solid #323835; border-radius:12px; box-shadow:0 10px 28px rgba\(15,18,16,\.22\);/)
    // the card's tabs: inset track, the neutral active segment
    expect(f).toMatch(/display: 'flex', padding: 3, borderRadius: 8, background: '#2A2F2C'/)
    expect(f).toMatch(/background: on \? '#3A403C' : 'transparent', fontSize: 13, fontWeight: on \? 500 : 400, color: on \? '#F2F4F1' : '#9AA29C'/)
  })
  it('ST-canvas: the canvas fills the window on the ground colour with the 20px dot grid; the old top bar, library panel and right panel frame are gone', () => {
    const c2 = read('canvas2/Canvas2.jsx'), app = read('App.jsx')
    expect(c2).toMatch(/style=\{\{ background: '#F4F3EF', cursor: effectiveCursor \}\}/)
    expect(c2).toMatch(/backgroundImage: 'radial-gradient\(#D9D6CC 1px, transparent 1\.2px\)', backgroundSize: '20px 20px'/)
    expect(/<TopBar|<RightPanel|<GeneratePanel|Back to hub/.test(app)).toBe(false)
    expect(app).toMatch(/<FloatingToolbar studio \/>/)
    expect(app).toMatch(/import '\.\/studio\/studio\.css'/)
  })
  it('ST-labels: Generate on an empty plan, Regenerate once racks exist; Check carries the count chip; Export is the mint primary', () => {
    const f = read('studio/StudioFrame.jsx')
    expect(f).toMatch(/const genLabel = hasRacks \? 'Regenerate' : 'Generate'/)
    expect(f).toMatch(/{ bg: '#5A2A20', fg: '#FFB4A3', n: e }/)
    expect(f).toMatch(/background: '#7BD3A4', color: '#0F2A1F', fontSize: 13, fontWeight: 600 \}\}>Export</)
  })
  it('ST-scrollbars: one global scrollbar style — thin, 8px, the mockup\'s thumb and border; no other scrollbar rule', () => {
    const css = read('studio/studio.css'), idx = read('index.css')
    expect(css).toMatch(/\* \{ scrollbar-width:thin; scrollbar-color:#3A403C transparent; \}/)
    expect(css).toMatch(/::-webkit-scrollbar \{ width:8px; height:8px; \}/)
    expect(css).toMatch(/::-webkit-scrollbar-thumb \{ background:#3A403C; border-radius:4px; border:2px solid #1F2321; \}/)
    expect(css).toMatch(/::-webkit-scrollbar-thumb:hover \{ background:#4A514D; \}/)
    expect(/::-webkit-scrollbar/.test(idx)).toBe(false)
  })
  it('ST-icons: every frame icon is the set\'s (iconData, generated from Icons.dc.html); no Lucide in the frame', () => {
    for (const f of FRAME) expect([f, /from 'lucide-react'/.test(read(f))]).toEqual([f, false])
    expect(read('studio/iconData.js')).toMatch(/^\/\/ GENERATED by scripts\/studio-icons\.mjs/)
    for (const n of ['Select', 'Pan', 'Fill racking', 'Row group', 'Split', 'Measure', 'Undo', 'Redo', 'Generate', 'Settings', 'Full screen']) expect([n, !!TOOLS[n]?.idle && !!TOOLS[n]?.active]).toEqual([n, true])
    for (const n of ['Floor plans', 'Racking', 'Ops', 'Structural', 'Safety', 'Zones', 'Blocks']) expect([n, !!RAIL[n]]).toEqual([n, true])
    // box style: solid shapes, crisp edges on rects
    expect(RAIL.Racking.body).toMatch(/shape-rendering="crispEdges"/)
  })
})
